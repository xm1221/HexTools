#!/usr/bin/env python3
"""Generate public/data/patterns.json for HexTools' HexParse input.

The pattern signatures come from hexdoc: every hexdoc-enabled mod publishes a
``*.patterns.hexdoc.json`` file inside its jar/package. We install the mods we
care about into a throwaway directory, scan for those files, and merge them.

Number literals (``num_<n>``) are generated by hexnumgen and committed to
``scripts/data/numbers_2000.json`` so that a normal build never needs Python.

Usage:
    uv pip install --target .vendor-hexdoc -r scripts/requirements.txt
    python3 scripts/generate_patterns.py

Optional extra mods can be installed the same way; failures are reported as
gaps instead of aborting the whole run.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / ".vendor-hexdoc"
OUT = ROOT / "public" / "data" / "patterns.json"
NUMBERS = ROOT / "scripts" / "data" / "numbers_2000.json"

# hexcasting is required; the rest are best-effort.
REQUIRED_PACKAGES = ["hexdoc-hexcasting==0.11.4.1.0"]
OPTIONAL_PACKAGES = [
    "hexdoc-hexal",
    "hexdoc-moreiotas",
    "hexdoc-hexparse",
    "hexdoc-miehex",
]


def install(packages: list[str], target: Path) -> list[str]:
    """Install packages into `target`; return the ones that failed."""
    failed: list[str] = []
    for package in packages:
        print(f"[install] {package}", file=sys.stderr)
        result = subprocess.run(
            [sys.executable, "-m", "pip", "install", "--quiet", "--target", str(target), package],
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            print(f"[gap] {package}: {result.stderr.strip().splitlines()[-1:]}", file=sys.stderr)
            failed.append(package)
    return failed


def find_pattern_files(target: Path) -> list[Path]:
    return sorted(target.rglob("*.patterns.hexdoc.json"))


def load_patterns(files: list[Path]) -> list[dict]:
    patterns: dict[str, dict] = {}
    for path in files:
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as e:
            print(f"[gap] could not read {path}: {e}", file=sys.stderr)
            continue
        entries = raw.get("patterns", raw) if isinstance(raw, dict) else raw
        if not isinstance(entries, list):
            continue
        for entry in entries:
            try:
                startdir = entry["startdir"]
                signature = entry["signature"]
                pattern_id = entry["id"]
            except KeyError:
                continue
            pattern_id = str(pattern_id)
            namespace, _, path_ = pattern_id.partition(":")
            aliases = sorted({pattern_id, path_ or pattern_id})
            record = {
                "id": pattern_id,
                "startdir": startdir,
                "signature": signature,
                "aliases": aliases,
                "source": str(path.relative_to(target)),
            }
            # Later files win only for identical ids, which should not happen.
            patterns[pattern_id] = record
    return sorted(patterns.values(), key=lambda p: p["id"])


def main() -> int:
    target = Path(os.environ.get("HEXDOC_VENDOR_DIR", VENDOR))
    target.mkdir(parents=True, exist_ok=True)

    if os.environ.get("SKIP_INSTALL") != "1":
        failed = install(REQUIRED_PACKAGES + OPTIONAL_PACKAGES, target)
        gaps = sorted(set(failed))
    else:
        gaps = []

    files = find_pattern_files(target)
    if not files:
        print(
            "error: no *.patterns.hexdoc.json found; install the mods first "
            "(or set SKIP_INSTALL=1 if .vendor-hexdoc is already populated)",
            file=sys.stderr,
        )
        return 1

    patterns = load_patterns(files)
    numbers = json.loads(NUMBERS.read_text(encoding="utf-8"))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        json.dumps(
            {
                "version": 1,
                "generated_from": len(files),
                "gaps": gaps,
                "patterns": patterns,
                "numbers": numbers,
            },
            ensure_ascii=False,
            separators=(",", ":"),
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(patterns)} patterns, {len(numbers)} numbers, {len(gaps)} gaps")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
