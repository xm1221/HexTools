#!/usr/bin/env python3
"""Generate public/data/patterns.json for HexTools' HexParse input.

The pattern signatures come from hexdoc: every hexdoc-enabled mod publishes a
``*.patterns.hexdoc.json`` file inside its package. We install every
``hexdoc-*`` addon listed in ``scripts/requirements.txt`` into a throwaway
directory (``--no-deps``, since we only need those JSON files), scan for them,
and merge them.

Bare aliases prefer ``hexcasting:``; otherwise the first-registered id wins and
any later colliding bare names are recorded under ``ambiguous``.

Number literals (``num_<n>``) are generated by hexnumgen and committed to
``scripts/data/numbers_2000.json`` so that a normal build never needs Python.

Usage:
    uv pip install --target .vendor-hexdoc --no-deps -r scripts/requirements.txt
    SKIP_INSTALL=1 python3 scripts/generate_patterns.py
    # or just:
    python3 scripts/generate_patterns.py
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / ".vendor-hexdoc"
OUT = ROOT / "public" / "data" / "patterns.json"
NUMBERS = ROOT / "scripts" / "data" / "numbers_2000.json"
REQUIREMENTS = ROOT / "scripts" / "requirements.txt"

REQ_LINE = re.compile(r"^\s*([A-Za-z0-9_.\-]+(?:==[^\s#]+)?)\s*(?:#.*)?$")


def read_requirements(path: Path) -> list[str]:
    packages: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        m = REQ_LINE.match(line)
        if m:
            packages.append(m.group(1))
    return packages


def package_name(spec: str) -> str:
    return spec.split("==", 1)[0].strip().lower()


def install(packages: list[str], target: Path) -> list[dict]:
    """Install each package with --no-deps; return gap records for failures."""
    gaps: list[dict] = []
    # Prefer uv when available; fall back to python -m pip.
    uv = shutil_which("uv")
    for package in packages:
        print(f"[install] {package}", file=sys.stderr)
        if uv:
            cmd = [
                uv,
                "pip",
                "install",
                "--quiet",
                "--python",
                sys.executable,
                "--target",
                str(target),
                "--no-deps",
                package,
            ]
        else:
            cmd = [
                sys.executable,
                "-m",
                "pip",
                "install",
                "--quiet",
                "--target",
                str(target),
                "--no-deps",
                package,
            ]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            err = (result.stderr or result.stdout or "").strip().splitlines()
            reason = err[-1] if err else f"exit {result.returncode}"
            print(f"[gap] {package}: {reason}", file=sys.stderr)
            gaps.append({"package": package, "reason": reason})
    return gaps


def shutil_which(cmd: str) -> str | None:
    from shutil import which

    return which(cmd)


def find_pattern_files(target: Path) -> list[Path]:
    files = sorted(target.rglob("*.patterns.hexdoc.json"))
    # hexcasting first so bare aliases prefer it when buildAliasIndex walks in order.
    def sort_key(p: Path) -> tuple:
        s = str(p).lower()
        return (0 if "hexcasting" in s and "hexcasting" == p.stem.split(".")[0] or "/hexcasting/" in s or "hexdoc_hexcasting" in s else 1, s)

    # More reliable: prefer paths under a hexdoc_hexcasting / hexcasting dist.
    def better_key(p: Path) -> tuple:
        parts = [x.lower() for x in p.parts]
        is_core = any(
            part in {"hexdoc_hexcasting", "hexcasting"} or part.startswith("hexdoc_hexcasting")
            for part in parts
        )
        return (0 if is_core else 1, str(p).lower())

    return sorted(files, key=better_key)


def load_patterns(files: list[Path], target: Path) -> tuple[list[dict], list[dict], dict[str, int]]:
    patterns: dict[str, dict] = {}
    bare_owner: dict[str, str] = {}
    ambiguous: list[dict] = []
    per_addon: Counter[str] = Counter()

    for path in files:
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as e:
            print(f"[gap] could not read {path}: {e}", file=sys.stderr)
            continue
        entries = raw.get("patterns", raw) if isinstance(raw, dict) else raw
        if not isinstance(entries, list):
            continue
        for entry in entries:
            try:
                startdir = entry["startdir"]
                signature = entry["signature"]
                pattern_id = entry["id"]
            except (KeyError, TypeError):
                continue
            pattern_id = str(pattern_id)
            namespace, _, path_ = pattern_id.partition(":")
            bare = path_ or pattern_id
            aliases = sorted({pattern_id, bare})
            record = {
                "id": pattern_id,
                "startdir": startdir,
                "signature": signature,
                "aliases": aliases,
                "source": str(path.relative_to(target)),
            }
            if pattern_id in patterns:
                # Same id from another file — keep first (hexcasting-first order).
                continue
            patterns[pattern_id] = record
            per_addon[namespace or "unknown"] += 1
            if bare in bare_owner and bare_owner[bare] != pattern_id:
                # Later bare collision; first owner (prefer hexcasting) wins at resolve time.
                ambiguous.append(
                    {
                        "alias": bare,
                        "kept": bare_owner[bare],
                        "skipped": pattern_id,
                    }
                )
            else:
                bare_owner[bare] = pattern_id

    ordered = sorted(
        patterns.values(),
        key=lambda p: (0 if p["id"].startswith("hexcasting:") else 1, p["id"]),
    )
    return ordered, ambiguous, dict(sorted(per_addon.items()))


def main() -> int:
    target = Path(os.environ.get("HEXDOC_VENDOR_DIR", VENDOR))
    target.mkdir(parents=True, exist_ok=True)

    packages = read_requirements(REQUIREMENTS)
    if not packages:
        print(f"error: no packages in {REQUIREMENTS}", file=sys.stderr)
        return 1

    if os.environ.get("SKIP_INSTALL") != "1":
        gaps = install(packages, target)
    else:
        gaps = []

    files = find_pattern_files(target)
    if not files:
        print(
            "error: no *.patterns.hexdoc.json found; install the mods first "
            "(or set SKIP_INSTALL=1 if .vendor-hexdoc is already populated)",
            file=sys.stderr,
        )
        return 1

    patterns, ambiguous, per_addon = load_patterns(files, target)
    numbers = json.loads(NUMBERS.read_text(encoding="utf-8"))

    # Packages that installed but contributed zero patterns (missing or empty file).
    failed_names = {package_name(g["package"]) for g in gaps}
    contrib_counts: Counter[str] = Counter()
    for f in files:
        pkg = None
        for part in f.parts:
            low = part.lower()
            if low.startswith("hexdoc_"):
                pkg = low.replace("_", "-")
                break
        if pkg is None:
            continue
        try:
            raw = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            contrib_counts[pkg] += 0
            continue
        entries = raw.get("patterns", raw) if isinstance(raw, dict) else raw
        n = len(entries) if isinstance(entries, list) else 0
        contrib_counts[pkg] += n
    installed_names = {package_name(p) for p in packages}
    empty = sorted(
        name
        for name in installed_names
        if name not in failed_names and contrib_counts.get(name, 0) == 0
    )

    OUT.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "version": 1,
        "generated_from": len(files),
        "packages": packages,
        "gaps": gaps,
        "empty_packages": empty,
        "per_addon": per_addon,
        "ambiguous": ambiguous,
        "patterns": patterns,
        "numbers": numbers,
    }
    OUT.write_text(
        json.dumps(payload, ensure_ascii=False, separators=(",", ":"), sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(
        f"wrote {OUT.relative_to(ROOT)}: {len(patterns)} patterns, "
        f"{len(numbers)} numbers, {len(gaps)} gaps, {len(ambiguous)} ambiguous, "
        f"{len(per_addon)} namespaces",
        file=sys.stderr,
    )
    for ns, n in per_addon.items():
        print(f"  {ns}: {n}", file=sys.stderr)
    if gaps:
        print("gaps:", file=sys.stderr)
        for g in gaps:
            print(f"  {g['package']}: {g['reason']}", file=sys.stderr)
    if empty:
        print("empty (installed, no pattern files):", file=sys.stderr)
        for name in empty:
            print(f"  {name}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
